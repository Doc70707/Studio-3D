// Dependency licence check + third-party notices.
//
// 1. Lists every package that ships inside the app (npm production deps and Rust crates).
// 2. Fails if any licence is copyleft (GPL/AGPL/SSPL...) or unknown, unless it is reviewed below.
// 3. Writes THIRD_PARTY_NOTICES.md. CI fails if the committed copy is out of date.
//
// Usage: node scripts/check-licenses.mjs [--no-cargo]
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const BLOCKED = /\b(A?GPL|SSPL|EUPL|OSL|CC-BY-NC|BUSL)\b/i;
// MPL-2.0 is file-level copyleft: fine to ship unmodified (some Tauri crates use it); changes to those files would have to be published.
const ALLOWED = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|0BSD|Apache-2\.0|Zlib|Unicode-3\.0|Unicode-DFS-2016|CC0-1\.0|BSL-1\.0|MPL-2\.0|Unlicense|CDLA-Permissive-2\.0)$/;

// Licences a human has reviewed. Each entry needs a reason (see docs/milestone-0/licensing-and-dependencies.md).
// Add "name@version": "reason" here only after a human has reviewed a licence the rules above reject.
const REVIEWED = {};

/** "MIT OR Apache-2.0" → ok if any alternative is allowed; "MIT AND X" → every part must be allowed. */
function verdict(expr) {
  if (!expr) return "unknown";
  const clean = expr.replace(/[()]/g, " ").replace(/\s+/g, " ").trim().replace(/ WITH [^ ]+/g, "");
  const alternatives = clean.split(/ OR |\//);
  const ok = alternatives.some((alt) => alt.split(" AND ").every((p) => ALLOWED.test(p.trim())));
  if (ok) return "ok";
  return BLOCKED.test(clean) ? "blocked" : "unknown";
}

function npmPackages() {
  const tree = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], { cwd: root, encoding: "utf8" }));
  const found = new Map();
  const walk = (deps = {}) => {
    for (const [name, info] of Object.entries(deps)) {
      if (!info.version || name.startsWith("@studio3d/")) {
        walk(info.dependencies);
        continue;
      }
      const key = `${name}@${info.version}`;
      if (found.has(key)) continue;
      const dir = join(root, "node_modules", name);
      const pkg = existsSync(join(dir, "package.json")) ? JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) : {};
      const licence = typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
      const file = existsSync(dir) ? readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f)) : undefined;
      found.set(key, {
        ecosystem: "npm",
        name,
        version: info.version,
        licence,
        repo: typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url,
        text: file ? readFileSync(join(dir, file), "utf8").trim() : undefined,
      });
      walk(info.dependencies);
    }
  };
  walk(tree.dependencies);
  return [...found.values()];
}

function cargoCrates() {
  const manifest = join(root, "apps/desktop/src-tauri/Cargo.toml");
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--manifest-path", manifest, "--filter-platform", "x86_64-pc-windows-msvc"], {
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  // Only crates reachable from our crate's normal (shipped) dependencies, not build tools.
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const shipped = new Set();
  const visit = (id) => {
    if (shipped.has(id)) return;
    shipped.add(id);
    for (const d of nodes.get(id)?.deps ?? []) if (d.dep_kinds.some((k) => k.kind === null)) visit(d.pkg);
  };
  visit(meta.resolve.root);
  return meta.packages
    .filter((p) => shipped.has(p.id) && p.source)
    .map((p) => ({ ecosystem: "crates.io", name: p.name, version: p.version, licence: p.license, repo: p.repository }));
}

const useCargo = !process.argv.includes("--no-cargo");
const all = [...npmPackages(), ...(useCargo ? cargoCrates() : [])].sort((a, b) =>
  `${a.ecosystem}${a.name}`.localeCompare(`${b.ecosystem}${b.name}`),
);

let failures = 0;
for (const p of all) {
  const v = REVIEWED[`${p.name}@${p.version}`] ? "ok" : verdict(p.licence);
  if (v !== "ok") {
    failures++;
    console.error(`${v.toUpperCase()}: ${p.ecosystem} ${p.name}@${p.version} licence "${p.licence ?? "none"}"`);
  }
}

const lines = [
  "# Third-party notices",
  "",
  "Studio 3D includes the following third-party software. Generated by `npm run licenses`; do not edit by hand.",
  "",
  "| Ecosystem | Package | Version | Licence |",
  "|---|---|---|---|",
  ...all.map((p) => `| ${p.ecosystem} | ${p.name} | ${p.version} | ${p.licence ?? "unknown"} |`),
  "",
  "## Licence texts (npm packages)",
  "",
  ...all
    .filter((p) => p.text)
    .flatMap((p) => [`### ${p.name}@${p.version}`, "", "```text", p.text, "```", ""]),
  "Rust crate licence texts are collected with cargo-about for release builds (planned before the private alpha).",
  "",
];
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), lines.join("\n"));

console.log(`${all.length} shipped dependencies checked (${all.filter((p) => p.ecosystem === "npm").length} npm, ${all.filter((p) => p.ecosystem !== "npm").length} Rust).`);
if (failures) {
  console.error(`${failures} dependency licence(s) need review. See docs/milestone-0/licensing-and-dependencies.md.`);
  process.exit(1);
}
console.log("All licences are permissive. THIRD_PARTY_NOTICES.md updated.");
